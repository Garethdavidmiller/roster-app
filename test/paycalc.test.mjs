// ── calcProRateFactor ─────────────────────────────────────────────────────────
// Reproduces getPeriods() arithmetic to get exact period dates for P51.
// P51 payday = Feb 13 2026 (noon) + 3 × 28 days = May 8 2026.
// FORMULA INVARIANT: periodCutoff is noon local; startDate is midnight local.
// Math.round on the 0.5-day offset always gives the correct calendar count.

describe('calcProRateFactor', () => {
  // Build P51 dates exactly as getPeriods() does in paycalc.js
  const anchor  = new Date(2026, 1, 13, 12, 0, 0);          // Feb 13 2026, noon local
  const p51pay  = new Date(anchor); p51pay.setDate(p51pay.getDate() + 3 * 28);
  const p51cut  = new Date(p51pay); p51cut.setDate(p51cut.getDate() - 6);
  const p51start= new Date(p51cut); p51start.setDate(p51start.getDate() - 27);
  // p51start = Sun Apr 5 2026 noon, p51cut = Sat May 2 2026 noon, 28-day window

  test('no startDate → 1.0 (full period)', () => {
    assert.equal(calcProRateFactor(null, p51start, p51cut), 1);
    assert.equal(calcProRateFactor(undefined, p51start, p51cut), 1);
  });

  test('startDate before period start → 1.0 (full period)', () => {
    assert.equal(calcProRateFactor(new Date(2026, 2, 1), p51start, p51cut), 1); // Mar 1
  });

  test('startDate = same calendar day as period start → 1.0', () => {
    // Apr 5 midnight < Apr 5 noon (p51start), so sd <= periodStart → return 1
    assert.equal(calcProRateFactor(new Date(2026, 3, 5), p51start, p51cut), 1);
  });

  test('a 20 April joiner: startDate Apr 20 midnight → 14/28 = 0.5 (matches payslip)', () => {
    // Apr 20 midnight → raw 12.5 → Math.round(12.5)=13 → daysEmployed=14 → 14/28=0.5
    // Verified: May 8 2026 payslip shows London Allowance £276.16 × 0.5 = £138.08 ✓
    const factor = calcProRateFactor(new Date(2026, 3, 20), p51start, p51cut);
    assert.equal(factor, 14 / 28);
    assert.equal(factor, 0.5);
  });

  test('startDate Apr 20 → contracted hours = Math.round(140 × 0.5) = 70', () => {
    const factor = calcProRateFactor(new Date(2026, 3, 20), p51start, p51cut);
    assert.equal(Math.round(140 * factor), 70);
  });

  test('startDate Apr 20 → London Allowance = £276.16 × 0.5 = £138.08', () => {
    const factor = calcProRateFactor(new Date(2026, 3, 20), p51start, p51cut);
    approx(276.16 * factor, 138.08, 'London Allowance pro-rated');
  });

  test('startDate after cutoff → 0.0 (not yet employed)', () => {
    assert.equal(calcProRateFactor(new Date(2026, 4, 5), p51start, p51cut), 0); // May 5
  });

  test('startDate = cutoff day midnight → 2/28 by the formula (one calendar day, counted two)', () => {
    // May 2 midnight → raw 0.5 → Math.round=1 → days=2 → 2/28 by the formula: the count is one more
    // than the calendar days, as for every in-period start (the docstring; paycalc-3-7 is on hold).
    // In practice Chiltern would never start someone on the last day of a period.
    const factor = calcProRateFactor(new Date(2026, 4, 2), p51start, p51cut);
    assert.equal(factor, 2 / 28);
  });

  // THE CUT-OFF IS INSIDE THE PERIOD (17 Nov 2026). Only a start AFTER it is "not yet employed"; a
  // start at the cut-off itself — the last moment the period covers — is employed for part of it.
  // Every other case here is a midnight start, which is never the same instant as a noon cut-off, so
  // `startDate > periodCutoff` could become `>=` with this file green. The formula's count at that
  // instant: no whole days to the cut-off, + 1 = 1 day of 28.
  test('a start AT the cut-off is inside the period — never 0', () => {
    const atCutoff = new Date(p51cut);
    assert.equal(calcProRateFactor(atCutoff, p51start, p51cut), 1 / 28);
    const justAfter = new Date(p51cut.getTime() + 1);
    assert.equal(calcProRateFactor(justAfter, p51start, p51cut), 0, 'a moment later, the next period');
  });

  test('Apr 19 midnight → 15/28 ≠ 0.5 (confirms Apr 20 is the correct startDate)', () => {
    // This was the v8.77 regression: changing Apr 20 → Apr 19 gave 53.6% not 50%
    const factor = calcProRateFactor(new Date(2026, 3, 19), p51start, p51cut);
    assert.equal(factor, 15 / 28);
    assert.notEqual(factor, 0.5);
  });

  test('totalDays is always 28 for a standard period', () => {
    // Internal check: (cutoff noon − start noon) = 27 whole days → +1 = 28
    const msPerDay  = 86400000;
    const totalDays = Math.round((p51cut - p51start) / msPerDay) + 1;
    assert.equal(totalDays, 28);
  });

  // THE SPRING CLOCK CHANGE (72-hour review). The count divided real milliseconds by 24 hours, and
  // a period that contains the last Sunday of March is one hour SHORT in UK local time — so a start
  // date before the change measured 12.458 days where the formula expects 12.5, rounded DOWN, and
  // the joiner lost a day of contracted hours, London Allowance and pension. Only a start date on
  // the far side of the change was right. This runs in a child process pinned to Europe/London,
  // because the defect cannot exist in the UTC the unit lane usually runs in — a test in-process
  // would pass with or without the fix and prove nothing.
  test('a joining period that crosses the spring clock change loses no day (Europe/London)', () => {
    const calcUrl = new URL('./paycalc-calc.js', REPO_ROOT_URL).href;
    const code = `import { calcProRateFactor, proRateDays } from ${JSON.stringify(calcUrl)};
      const cases = [
        // P50 of 2025/26's successor: start Sun 8 Mar 2026, cutoff Sat 4 Apr 2026 — change 29 Mar.
        [new Date(2026, 2, 8, 12), new Date(2026, 3, 4, 12), [9, 20, 28, 29, 30]],
        // The 2027 twin: start Sun 7 Mar 2027, cutoff Sat 3 Apr 2027 — change 28 Mar.
        [new Date(2027, 2, 7, 12), new Date(2027, 3, 3, 12), [15, 27, 28, 29]],
      ];
      const out = cases.map(([s, c, days]) => days.map(d => {
        const sd = new Date(s.getFullYear(), 2, d);
        return [calcProRateFactor(sd, s, c) * 28, proRateDays(sd, s, c).daysEmployed];
      }));
      console.log(JSON.stringify(out));`;
    const out = JSON.parse(String(execFileSync(process.execPath, ['--input-type=module', '-e', code],
      { env: { ...process.env, TZ: 'Europe/London' } })));
    // Calendar days from the start date to the cutoff inclusive, +1 — the formula's documented
    // (payslip-verified) reading, now independent of the clock change. Each pair is [factor×28,
    // the day count the joiner notice prints]; the two must agree.
    const want = [[28, 17, 9, 8, 7], [21, 9, 8, 7]];
    out.forEach((row, i) => row.forEach(([f, n], j) => {
      approx(f, want[i][j], `case ${i}.${j} factor×28`);
      assert.equal(n, want[i][j], `case ${i}.${j} joiner-notice day count`);
    }));
  });
});

// ── Reference 2025/26 payslip integration ─────────────────────────────────────
// Actual payslip figures from the gitignored test-fixtures/payslip-actuals.local.js.
// gross = post-pension sacGross (matches "Taxable Pay" on payslip).
// Tax and NI are tested non-cumulatively: actual payroll uses cumulative PAYE,
// so small per-period differences (up to ~£1 tax, ~20p NI) are expected and
// acceptable. Any larger gap would indicate a formula regression.
// Student loan IS tested — the reference member is on Plan 1 (confirmed); the clean-period SL
// deductions are locked by the `PAYSLIP_ACTUALS.sl` regression in the computeSL block above.
// Net take-home is reconciled below (net = gross − tax − NI − SL).
// NOTE: The HMRC-floor test above asserts P20 NON-CUMULATIVE tax = £809.60, while
// PAYSLIP_ACTUALS records the actual payslip tax of £809.71 for the same period.
// These do not conflict: £809.71 is the cumulative payslip figure (the source of
// truth), £809.60 is the non-cumulative floored estimate, and the 11p gap is the
// expected cumulative-PAYE drift documented above. Confirmed by Gareth (Jun 2026).

describe('payslip integration (non-cumulative estimates against real payslips)', () => {
  // Derived from the real payslip fixture (test-fixtures/payslip-actuals.local.js) — the single
  // source of truth for this regression net. These figures lived in PAYSLIP_ACTUALS in the served
  // roster-data.js until v14.68, moved to a hosting-excluded fixture then, and left the tree
  // entirely at v23.71 (the Pages mirror serves the repo root, so an ignore list could not
  // express the decision for both origins). Object insertion order is payday-ascending, preserved.
  if (!PAYSLIP_ACTUALS) {
    test('SKIPPED — the thirteen real payslips are not on this checkout', (t) =>
      t.skip('real payslip fixture absent — see the note at the top of this file'));
    return;
  }
  const actuals = Object.entries(PAYSLIP_ACTUALS)
    .map(([date, v]) => ({ date, gross: v.gross, tax: v.tax, ni: v.ni }));

  for (const p of actuals) {
    test(`${p.date}: tax within £1 of payslip`, () => {
      const { tax } = computeTax(p.gross, '1257L', T25);
      approx(tax, p.tax, `tax ${p.date}`, 1.00);
    });

    test(`${p.date}: NI within 20p of payslip`, () => {
      const ni = computeNI(p.gross, T25.ni);
      approx(ni, p.ni, `NI ${p.date}`, 0.20);
    });
  }

  // YEAR TO DATE MODE AGAINST THE REAL PAYROLL (Oct 2026). The non-cumulative tests above allow £1
  // because they compare a one-period estimate with a cumulative payroll; this one does not have that
  // excuse. Each payslip is estimated the way a member would — the Year to Date totals summed from the
  // payslips before it — so it is the cumulative path doing what the real payroll did. Before HMRC's
  // (code × 10) + 9 reached this path it ran high EVERY period, worst £3.75 by March, inside the old £5
  // tolerance of the half-pair control below. Measured worst after: 25p.
  test('Year to Date mode: every payslip estimated within 30p of what payroll deducted', () => {
    let ytdPay = 0, ytdTax = 0, n = 0;
    for (const [date, v] of Object.entries(PAYSLIP_ACTUALS)) {
      n++;
      const { tax, usingCumulative } = computeTax(v.gross, '1257L', T25, { ytdPay, ytdTax, periodN: n });
      assert.equal(usingCumulative, true);
      approx(tax, v.tax, `Year to Date tax ${date}`, 0.30);
      ytdPay += v.gross; ytdTax += v.tax;
    }
  });

  // Take-home identity: every real payslip's own figures must reconcile as
  //   net = Taxable Pay − Tax − NI − Student Loan.
  // This locks the fixture's internal consistency (every per-field assertion above leans on
  // it) and documents the exact formula the calculator uses for the £ take-home it displays —
  // the headline figure staff read. Combined with the per-field tax/NI/SL tests, it
  // transitively confirms the code composes to the real take-home. Tolerance covers minor
  // payslip rounding (largest observed drift ~28p). (v17.24 — closes the "net never asserted" gap.)
  const withNet = Object.entries(PAYSLIP_ACTUALS).map(([date, v]) => ({ date, ...v }));
  for (const p of withNet) {
    test(`${p.date}: net reconciles as gross − tax − NI − SL`, () => {
      approx(p.gross - p.tax - p.ni - p.sl, p.net, `net ${p.date}`, 0.50);
    });
  }
});
