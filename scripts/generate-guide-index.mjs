// @ts-check
/**
 * generate-guide-index.mjs — `npm run generate:guide-index`
 *
 * Rebuilds guide-index.js (the committed cross-guide search index) from the five guide pages.
 * Run it in the SAME COMMIT as any guide-content change — guide-index-parity.test.mjs fails a
 * stale index, exactly as sw-asset-check does for roster-members.json.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { buildGuideIndex } from './guide-index-lib.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const units = buildGuideIndex(name => readFileSync(join(root, name), 'utf8'));

const body = units.map(u => '    ' + JSON.stringify(u)).join(',\n');
const out = `// @ts-check
// GENERATED by scripts/generate-guide-index.mjs — do NOT hand-edit; run \`npm run generate:guide-index\`.
// The cross-guide search index: one unit per guide section or card, with the provisional evidence
// states the page itself declares. Read by nav-guide-search.js (lazy-loaded from the nav drawer);
// matched against the guide HTML by guide-index-parity.test.mjs. Shape: guide-search.js GuideIndexUnit.
/** @type {import('./guide-search.js').GuideIndexUnit[]} */
export const GUIDE_INDEX = [
${body},
];
`;
writeFileSync(join(root, 'guide-index.js'), out);
console.log(`guide-index.js: ${units.length} units, ${out.length} bytes`);
